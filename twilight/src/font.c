#include <twilight/font.h>
#include <twilight/framebuffer.h>

#define GLYPH_WIDTH 8u
#define GLYPH_HEIGHT 16u
#define FONT_SCALE 2u
#define ADVANCE ((GLYPH_WIDTH + 1u) * FONT_SCALE)

struct glyph {
    char character;
    uint8_t rows[GLYPH_HEIGHT];
};

/*
 * A deliberately small bring-up font. It is drawn into the linear framebuffer,
 * never through VGA text mode. The 2x scaling produces a 16x32 Linux-console/
 * Terminus-like size while keeping the renderer tiny and easy to replace later.
 */
static const struct glyph glyphs[] = {
    {'H', {0x00,0x00,0x42,0x42,0x42,0x42,0x7e,0x42,0x42,0x42,0x42,0x42,0x00,0x00,0x00,0x00}},
    {'e', {0x00,0x00,0x00,0x00,0x3c,0x42,0x42,0x7e,0x40,0x40,0x42,0x3c,0x00,0x00,0x00,0x00}},
    {'l', {0x00,0x00,0x18,0x08,0x08,0x08,0x08,0x08,0x08,0x08,0x08,0x1c,0x00,0x00,0x00,0x00}},
    {'o', {0x00,0x00,0x00,0x00,0x3c,0x42,0x42,0x42,0x42,0x42,0x42,0x3c,0x00,0x00,0x00,0x00}},
    {',', {0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x18,0x18,0x08,0x10,0x00,0x00,0x00}},
    {'W', {0x00,0x00,0x81,0x81,0x81,0x81,0x81,0x99,0x99,0xa5,0xa5,0x42,0x00,0x00,0x00,0x00}},
    {'r', {0x00,0x00,0x00,0x00,0x2c,0x32,0x20,0x20,0x20,0x20,0x20,0x20,0x00,0x00,0x00,0x00}},
    {'d', {0x00,0x00,0x02,0x02,0x3a,0x46,0x42,0x42,0x42,0x42,0x46,0x3a,0x00,0x00,0x00,0x00}},
    {'!', {0x00,0x00,0x18,0x18,0x18,0x18,0x18,0x18,0x18,0x00,0x18,0x18,0x00,0x00,0x00,0x00}},
};

static const uint8_t *glyph_for(char c) {
    if (c == ' ') {
        return NULL;
    }

    for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i) {
        if (glyphs[i].character == c) {
            return glyphs[i].rows;
        }
    }
    return NULL;
}

static void draw_glyph(char c, size_t x, size_t y,
                       uint8_t red, uint8_t green, uint8_t blue) {
    const uint8_t *rows = glyph_for(c);
    if (rows == NULL) {
        return;
    }

    for (size_t gy = 0; gy < GLYPH_HEIGHT; ++gy) {
        for (size_t gx = 0; gx < GLYPH_WIDTH; ++gx) {
            if ((rows[gy] & (uint8_t)(0x80u >> gx)) == 0) {
                continue;
            }
            for (size_t sy = 0; sy < FONT_SCALE; ++sy) {
                for (size_t sx = 0; sx < FONT_SCALE; ++sx) {
                    framebuffer_put_pixel(x + gx * FONT_SCALE + sx,
                                          y + gy * FONT_SCALE + sy,
                                          red, green, blue);
                }
            }
        }
    }
}

void font_draw_string(const char *text, size_t x, size_t y,
                      uint8_t red, uint8_t green, uint8_t blue) {
    if (text == NULL) {
        return;
    }

    size_t cursor_x = x;
    for (size_t i = 0; text[i] != '\0'; ++i) {
        draw_glyph(text[i], cursor_x, y, red, green, blue);
        cursor_x += ADVANCE;
    }
}
